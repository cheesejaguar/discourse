  /**
   * Generate a QR code challenge for Alien.org authentication
   * Users scan this with their Alien app to authenticate
   */
  async generateChallenge(): Promise<{ challengeId: string; qrCodeUrl: string; expiresAt: Date }> {
    const challengeId = crypto.randomUUID();
    const nonce = crypto.randomBytes(32).toString('hex');
    const timestamp = Date.now();
    const expiresAt = new Date(timestamp + 5 * 60 * 1000); // 5 minutes

    // In production, this would call Alien's API to generate a challenge
    // For now, we return a mock challenge
    const qrCodeData = JSON.stringify({
      appId: this.appId,
      challengeId,
      nonce,
      timestamp,
      callbackUrl: `${config.corsOrigin}/auth/callback`,
    });

    // The QR code URL would be generated by Alien's API
    // Mock: encode as a data URL for development
    const qrCodeUrl = `alien://verify?data=${encodeURIComponent(Buffer.from(qrCodeData).toString('base64'))}`;

    return {
      challengeId,
      qrCodeUrl,
      expiresAt,
    };
  }

  /**
   * Verify an Alien.org authentication payload
   * This validates the cryptographic signature from the Alien app
   */
  async verifyPayload(payload: AlienAuthPayload): Promise<AlienVerificationResult> {
    try {
      // Validate timestamp (must be within last 5 minutes)
      const now = Date.now();
      const fiveMinutesAgo = now - 5 * 60 * 1000;

      if (payload.timestamp < fiveMinutesAgo || payload.timestamp > now) {
        return {
          isValid: false,
          error: 'Authentication payload has expired',
        };
      }

      // In production, this would verify the signature using Alien's public key
      // and confirm the alienId is valid through their CHVP (Continuous Human Verification Protocol)

      // Mock verification for development
      if (config.isDev) {
        // In dev mode, accept any payload with a valid structure
        if (payload.alienId && payload.signature && payload.nonce) {
          return {
            isValid: true,
            alienId: payload.alienId,
          };
        }
      }

      // Production: Call Alien's verification endpoint
      const verificationResult = await this.callAlienVerificationAPI(payload);
      return verificationResult;
    } catch (error) {
      console.error('Alien verification error:', error);
      return {
        isValid: false,
        error: 'Verification failed',
      };
    }
  }

